/** 覆盖 tools/extract-deployment.mjs --check。它曾因两个互不相干的原因同时红：
 * 不带参数时两个 profile 声明了同一 agent-loop 行（工具拒绝了歧义，而不是接受「一个部署一个值」）；
 * 以及显式参数那条路。这里把这两种情况都钉住。 */

import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const PLUGIN = path.join(HERE, '..')
const TOOL = path.join(PLUGIN, 'tools', 'extract-deployment.mjs')
const SNAPSHOT = path.join(PLUGIN, 'lib', 'template', 'deployment.json')
const LOOP_ID = 'agent-loop'

/** The `loop` row as shipped in `lib/template/deployment.json`. */
async function snapshotLoop() {
  return JSON.parse(await readFile(SNAPSHOT, 'utf8')).loop
}

/** A profile patch that declares `loop` as its only `agent-loop` row. */
function patchFor(loop) {
  const lines = [
    '# fixture: generated by tests/tools.test.mjs from lib/template/deployment.json',
    '- id: some-other-row',
    '  disabled: true',
    `- id: ${loop.id}`,
    `  name: "${loop.name}"`,
    '  config:',
    `    agents: ${JSON.stringify(loop.config.agents)}`,
    `    maxParallelToolCalls: ${JSON.stringify(loop.config.maxParallelToolCalls)}`,
    `  disabled: ${JSON.stringify(loop.disabled)}`,
    '',
  ]
  return lines.join('\n')
}

/** A temp directory under the plugin, so js-yaml resolves from here. */
async function scratch() {
  return mkdtemp(path.join(PLUGIN, '.tmp-tools-'))
}

function run(args, env = {}) {
  const result = spawnSync(process.execPath, [TOOL, ...args], {
    cwd: PLUGIN,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  })
  return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' }
}

test('C1: --check 带显式 patch 时，内容一致即 exit 0（修复前因 profile:null 假 drift）', async () => {
  const dir = await scratch()
  try {
    const file = path.join(dir, 'web.cordis.patch.yml')
    await writeFile(file, patchFor(await snapshotLoop()), 'utf8')

    const { status, stdout } = run(['--check', file])
    assert.equal(status, 0, stdout)
    assert.match(stdout, /--check: in sync with/)
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('C1: profile patch 里出现 !!js 门时仍能解析（预设副本会带进来）', async () => {
// 用户把自己的预设副本插进 cordis.patch.yml 后，补丁里会出现 !!js 平台门。
// 裸 js-yaml 会抛 unknown tag !<tag:yaml.org,2002:js>，--check 直接崩 —— 工具必须自己注册这个标签。
  const dir = await scratch()
  try {
    const file = path.join(dir, 'gated.cordis.patch.yml')
    const gated = [
      patchFor(await snapshotLoop()),
      '- insert:',
      '    - id: preset-user',
      "      name: '@deepseek-ai/dsh-agent-preset'",
      '      config:',
      '        id: user',
      '        plugins:',
      '          - id: tool-pwsh',
      "            name: '@deepseek-ai/dsh-tool-pwsh'",
      "            disabled: !!js process.platform !== 'win32'",
      '',
    ].join('\n')
    await writeFile(file, gated, 'utf8')

    const { status, stdout, stderr } = run(['--check', file])
    assert.equal(status, 0, `${stdout}\n${stderr}`)
    assert.match(stdout, /--check: in sync with/)
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('C1: 人工改一个字节 → exit 1，且指出真正变化的那一项', async () => {  const dir = await scratch()
  try {
    const loop = await snapshotLoop()
    const drifted = { ...loop, config: { ...loop.config, maxParallelToolCalls: loop.config.maxParallelToolCalls + 1 } }
    const file = path.join(dir, 'drifted.cordis.patch.yml')
    await writeFile(file, patchFor(drifted), 'utf8')

    const { status, stdout } = run(['--check', file])
    assert.equal(status, 1, stdout)
    assert.match(stdout, /differs from/)
    assert.match(stdout, /loop\.config: /)
    assert.match(stdout, /loop\.\w+.*→/) // old → new, not the unchanged field
    assert.ok(
      !/loop\.config: \{[^}]*\} → \{\1\}/.test(stdout),
      'the diff must not print an unchanged value on both sides',
    )
  } finally {
    await rm(dir, { recursive: true, force: true })
  }
})

test('C1: 无参运行时，多个 profile 声明同一行不再报错（修复前直接抛 several …）', async () => {
  const home = await scratch()
  try {
    const loop = await snapshotLoop()
    for (const profile of ['teamtest', 'web']) {
      const dir = path.join(home, 'profiles', profile)
      await mkdir(dir, { recursive: true })
      await writeFile(path.join(dir, 'cordis.patch.yml'), patchFor(loop), 'utf8')
    }

    const { status, stdout, stderr } = run(['--check'], { DSH_HOME: home })
    assert.equal(status, 0, `${stdout}\n${stderr}`)
    assert.match(stdout, /--check: in sync with/)
    // `web` breaks the tie, and the other profile is only a note.
    assert.match(stdout, /profiles[\\/]web[\\/]cordis\.patch\.yml/)
  } finally {
    await rm(home, { recursive: true, force: true })
  }
})

test('C1: 两个 profile 的 agent-loop 行真的不同才报错，并列出各自的值', async () => {
  const home = await scratch()
  const outDir = await scratch()
  try {
    const loop = await snapshotLoop()
    const other = { ...loop, config: { ...loop.config, maxParallelToolCalls: loop.config.maxParallelToolCalls + 3 } }
    for (const [profile, row] of [['web', loop], ['teamtest', other]]) {
      const dir = path.join(home, 'profiles', profile)
      await mkdir(dir, { recursive: true })
      await writeFile(path.join(dir, 'cordis.patch.yml'), patchFor(row), 'utf8')
    }

// 快照里的来源故意指向不存在的文件：没有「记录下来的来源」可跟随时，扫描才是唯一依据，真歧义必须报错。
// 仓里那份快照记的是相对 DSH_HOME 的路径（开源形态），在临时 home 下会解析到 web 那份、不再有歧义。
// 所以这条用例自带一份失效来源的快照，才测得到原本要测的东西。
    const out = path.join(outDir, 'deployment.json')
    await writeFile(
      out,
      JSON.stringify({ source: { patch: path.join(home, 'profiles', 'web', 'gone.yml'), profile: 'web' }, loop }, null, 2),
      'utf8',
    )

    const { status, stdout, stderr } = run(['--check'], { DSH_HOME: home, TEAM_DEPLOYMENT_SNAPSHOT: out })
    const output = `${stdout}\n${stderr}`
    assert.notEqual(status, 0, output)
    assert.match(output, /profiles disagree about agent-loop/)
    assert.match(output, /pass one explicitly/)
  } finally {
    await rm(home, { recursive: true, force: true })
    await rm(outDir, { recursive: true, force: true })
  }
})

test('A: --check 先跟随快照记录的来源，本机别的 profile 值不同也不影响', async () => {
  const home = await scratch()
  const outDir = await scratch()
  try {
    const loop = await snapshotLoop()
    const other = { ...loop, config: { ...loop.config, maxParallelToolCalls: loop.config.maxParallelToolCalls + 3 } }
    const web = path.join(home, 'profiles', 'web', 'cordis.patch.yml')
    const teamtest = path.join(home, 'profiles', 'teamtest', 'cordis.patch.yml')
    for (const [file, row] of [[web, loop], [teamtest, other]]) {
      await mkdir(path.dirname(file), { recursive: true })
      await writeFile(file, patchFor(row), 'utf8')
    }

    const out = path.join(outDir, 'deployment.json')
    await writeFile(out, JSON.stringify({ source: { patch: web, profile: 'web' }, loop }, null, 2), 'utf8')

// 没有这条时，web 与 teamtest 内容不同会让扫描直接抛错（两个 profile 值不同步的处境）。
    const { status, stdout, stderr } = run(['--check'], { DSH_HOME: home, TEAM_DEPLOYMENT_SNAPSHOT: out })
    assert.equal(status, 0, `${stdout}\n${stderr}`)
    assert.match(stdout, /--check: in sync with/)
    assert.match(stdout, /profiles[\\/]web[\\/]cordis\.patch\.yml/)
  } finally {
    await rm(home, { recursive: true, force: true })
    await rm(outDir, { recursive: true, force: true })
  }
})

