/**
 * 刷新 tests/fixtures/presets/<mode>.plugins.json 四份测试夹具。
 * 运行时角色组合从 Loader 现场读取，这四份只是测试的输入；不接进 npm test，
 * dsh 升级不能让测试变红，需要时手工跑再 review diff。
 * 用法：node tools/sync-presets.mjs [--check] [--only <mode>] [<preset.yml>]
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { MODES } from '../lib/template.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.join(HERE, '..', 'tests', 'fixtures', 'presets')

function outPath(mode) {
  return path.join(OUT_DIR, `${mode}.plugins.json`)
}

/** 候选部署，新→旧，无参数时按这个顺序找。 */
function candidateDshRoots() {
  const roots = []
  if (process.env.DSH_INSTALL_ROOT) roots.push(process.env.DSH_INSTALL_ROOT)
  if (process.env.APPDATA) roots.push(path.join(process.env.APPDATA, 'npm', 'node_modules', '@deepseek-ai', 'dsh'))
  roots.push('/usr/local/lib/node_modules/@deepseek-ai/dsh')
  roots.push('/usr/lib/node_modules/@deepseek-ai/dsh')
  return roots
}

function locatePreset(mode, explicit) {
  if (explicit) return path.resolve(explicit)
  for (const root of candidateDshRoots()) {
    if (!existsSync(root)) continue
    const preset = path.join(root, 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', `${mode}.patch.yml`)
    if (existsSync(preset)) return preset
  }
  throw new Error(`${mode}.patch.yml not found; pass its path as the first argument`)
}

/** 拥有该 preset 的部署，js-yaml 也从这里解析。 */
function locateRequireAnchor(presetPath) {
  let dir = path.dirname(presetPath)
  while (dir !== path.dirname(dir)) {
    if (existsSync(path.join(dir, 'package.json'))) return path.join(dir, 'package.json')
    dir = path.dirname(dir)
  }
  throw new Error(`no package.json above ${presetPath}`)
}

function loadYaml(presetPath) {
// js-yaml 是 dsh 部署的依赖而不是本插件的，所以从部署目录解析，
// 不能按本文件的位置去找。
  const anchor = locateRequireAnchor(presetPath)
  const require = createRequire(anchor)
  return require('js-yaml')
}

/** `!!js <expr>` → `{ __js__: '<expr>' }`，其它 tag 原样保留。 */
function jsTypeFor(yaml) {
  return new yaml.Type('tag:yaml.org,2002:js', {
    kind: 'scalar',
    resolve: (data) => typeof data === 'string' && data.length > 0,
    construct: (data) => ({ __js__: data }),
  })
}

/** 去掉 extractedAt（每次都变）与 file（本机绝对路径，不能提交进公开仓库）。 */
function sourceOf(snapshot) {
  const { declarationId, plugin, presetId, order } = snapshot.source
  return { declarationId, plugin, presetId, order }
}

function byId(rows) {
  return new Map(rows.map((row) => [row.id, row]))
}

async function extract(mode, explicit) {
  const presetPath = locatePreset(mode, explicit)
  const yaml = loadYaml(presetPath)
  const schema = yaml.DEFAULT_SCHEMA.extend([jsTypeFor(yaml)])

  const document = yaml.load(await readFile(presetPath, 'utf8'), { schema })
  const declaration = document?.[0]?.insert?.find((row) => row?.config?.plugins)

  if (!declaration) throw new Error(`${presetPath}: no row with config.plugins found`)

  const snapshot = {
    $comment:
      'Generated by tools/sync-presets.mjs — do not edit by hand. ' +
      '`{ "__js__": <expr> }` stands for a `!!js` scalar from the source patch.',
    source: {
      declarationId: declaration.id,
      plugin: declaration.name,
      presetId: declaration.config.id,
      order: declaration.config.order ?? null,
      extractedAt: new Date().toISOString(),
    },
    plugins: declaration.config.plugins,
  }

  const rows = snapshot.plugins.length
  const nested = snapshot.plugins.reduce((n, row) => n + (Array.isArray(row.config) ? row.config.length : 0), 0)
  return { mode, presetPath, snapshot, rows, nested }
}

/** 只比对不写盘，有差异就非 0 退出。 */
async function reportDrift({ mode, presetPath, snapshot, rows, nested }) {
  let existing
  try {
    existing = JSON.parse(await readFile(outPath(mode), 'utf8'))
  } catch (error) {
    console.log(`${mode}: --check cannot read ${outPath(mode)} (${error.code ?? error.message}); run without --check first`)
    process.exitCode = 1
    return
  }

  const notes = []
  const before = sourceOf(existing)
  const after = sourceOf(snapshot)
  for (const key of Object.keys(after)) {
    if (JSON.stringify(before[key]) !== JSON.stringify(after[key])) {
      notes.push(`source.${key}: ${JSON.stringify(before[key])} → ${JSON.stringify(after[key])}`)
    }
  }

  const oldRows = byId(existing.plugins ?? [])
  const newRows = byId(snapshot.plugins)
  for (const id of oldRows.keys()) if (!newRows.has(id)) notes.push(`row removed: ${id}`)
  for (const id of newRows.keys()) if (!oldRows.has(id)) notes.push(`row added: ${id}`)
  for (const [id, row] of newRows) {
    const old = oldRows.get(id)
    if (old && JSON.stringify(old) !== JSON.stringify(row)) notes.push(`row changed: ${id}`)
  }

  if (notes.length === 0) {
    console.log(`${mode}: --check in sync with ${presetPath} (${rows} top-level rows, ${nested} nested rows)`)
    return
  }
  console.log(`${mode}: --check ${outPath(mode)} differs from ${presetPath} — ${notes.length} change(s):`)
  for (const note of notes) console.log(`  ${note}`)
  console.log('  run without --check to regenerate, then review the diff')
  process.exitCode = 1
}

async function write({ mode, presetPath, snapshot, rows, nested }) {
  await mkdir(OUT_DIR, { recursive: true })
  await writeFile(outPath(mode), `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8')
  console.log(
    `${path.basename(outPath(mode))} written: ${rows} top-level rows, ${nested} nested rows, from ${presetPath}`,
  )
}

const args = process.argv.slice(2)
const checkOnly = args.includes('--check')
const onlyIndex = args.indexOf('--only')
const only = onlyIndex >= 0 ? args[onlyIndex + 1] : undefined
const explicit = args.find((arg) => !arg.startsWith('--') && arg !== only)

if (only !== undefined && !MODES.some((mode) => mode.id === only)) {
  console.error(`unknown mode: ${only} (expected one of ${MODES.map((mode) => mode.id).join(', ')})`)
  process.exit(2)
}

const wanted = only === undefined ? MODES.map((mode) => mode.id) : [only]

for (const mode of wanted) {
// 位置参数只对单个 preset 有意义，作用在 --only 选中的模式上。
  const result = await extract(mode, explicit)
  if (checkOnly) await reportDrift(result)
  else await write(result)
}
